"""Compile the ten Russian-language workshop series for the offline application."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COURSES = {"bim","revit","navisworks","autocad","civil3d","practice","manager","revitserver","english","software"}


def read_catalog():
    catalog = {}
    for line in (ROOT / "content/workshops.txt").read_text(encoding="utf-8-sig").splitlines():
        if not line.strip():
            continue
        if line.startswith("[") and line.endswith("]"):
            course = line[1:-1]
            if course in catalog:
                raise ValueError(f"Duplicate course {course}")
            catalog[course] = []
        else:
            cells = [cell.strip() for cell in line.split("|")]
            if len(cells) != 4 or not all(cells):
                raise ValueError(line)
            catalog[course].append(cells)
    if set(catalog) != COURSES or any(len(rows) != 10 for rows in catalog.values()):
        raise ValueError("Expected ten lessons per original course")
    return catalog


def make_lesson(course, rows, i):
    name, case, action, result = rows[i]
    # Scope distractors to the same discipline. Rotate answer positions deterministically.
    def pick(prompt, field, offset):
        options = [rows[(i + d) % len(rows)][field] for d in (0, offset, offset + 1)]
        shift = (i + offset) % len(options)
        return dict(type="single", q=prompt, options=options[shift:] + options[:shift],
                    answer=(-shift) % len(options), explain=f"{action} {result}")
    questions = [
        pick(case + " Какое действие соответствует этой ситуации?", 2, 1),
        pick("Как подтвердить результат работы по теме «" + name + "»?", 3, 2),
        pick("Для какой исходной ситуации подходит действие: " + action, 1, 3),
        pick("Какой результат ожидается после действия: " + action, 3, 4),
        pick("Какую проверку описывает критерий: " + result, 0, 5),
        pick("Какое действие приведёт к результату: " + result, 2, 6),
    ]
    return dict(id=f"{course}-workshop-{i+1:02}", title=name, minutes=6, level="Практика",
                goal=f"Разобрать ситуацию «{name}», выбрать действие и проверить результат.", tags=[name, "практическая задача"], terms=[],
                blocks=[dict(type="workshop", course=course, number=i+1),
                        dict(type="note", kind="tip", title="Исходные данные", text=case),
                        dict(type="steps", title="Самостоятельная работа", items=[
                            "Опишите, что в этой ситуации требуется выяснить или изменить.",
                            "Назовите действие и проверяемый признак успеха до чтения разбора."]),
                        dict(type="solution", title="Показать разбор", text=action),
                        dict(type="solution", title="Сверить результат", text=result)],
                questions=questions)


def main():
    catalog = {k:[make_lesson(k, rows, i) for i in range(len(rows))]
               for k, rows in read_catalog().items()}
    script = "/* Generated by tools/build_workshops.py */\n(() => {\nconst series = " + json.dumps(catalog, ensure_ascii=False, separators=(",",":")) + ";\nfor (const course of window.BIM_CONTENT.courses) course.lessons.push(...series[course.id]);\n})();\n"
    (ROOT / "data/workshops.js").write_text(script, encoding="utf-8")


if __name__ == "__main__":
    main()

